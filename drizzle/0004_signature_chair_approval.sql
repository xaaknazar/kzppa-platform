-- Окончательность заключения: Комиссия работает без ЭЦП — заключение становится окончательным
-- после утверждения председателем в платформе. Меняется только незаданная политика; выбор,
-- сделанный администратором в настройках, не трогается. Уже подготовленные PDF не меняются.
UPDATE organizations
SET policies = coalesce(policies, '{}'::jsonb) || '{"signature": "chair_approval"}'::jsonb
WHERE coalesce(policies->>'signature', '') = '';
